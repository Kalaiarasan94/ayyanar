const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const publicDir = path.join(rootDir, 'public');
const distDir = path.join(rootDir, 'dist');
const constantsDir = path.join(rootDir, 'constants');

const isSyncOnly = process.argv.includes('--sync-dist') || process.argv.includes('--sync-dist-only');

const publicVersionPath = path.join(publicDir, 'version.json');
const constantsPath = path.join(constantsDir, 'buildInfo.ts');
const publicSwPath = path.join(publicDir, 'sw.js');

let versionData;

if (isSyncOnly && fs.existsSync(publicVersionPath)) {
  try {
    versionData = JSON.parse(fs.readFileSync(publicVersionPath, 'utf-8'));
    console.log('[version] Syncing existing build version to dist -> buildId:', versionData.buildId);
  } catch (e) {
    console.warn('[version] Failed to parse existing version.json, creating new buildId');
  }
}

if (!versionData) {
  const timestamp = Date.now();
  const buildDate = new Date().toISOString();
  const buildId = `${timestamp}`;
  const version = '1.2.0';

  versionData = {
    version,
    buildId,
    buildTime: timestamp,
    buildDate,
  };

  // 1. Write frontend/constants/buildInfo.ts (embedded into client bundle)
  const buildInfoContent = `// Auto-generated by scripts/generate-build-version.js - DO NOT EDIT MANUALLY
export const BUILD_INFO = {
  version: '${versionData.version}',
  buildId: '${versionData.buildId}',
  buildTime: ${versionData.buildTime},
  buildDate: '${versionData.buildDate}',
};
`;
  fs.writeFileSync(constantsPath, buildInfoContent, 'utf-8');
  console.log('[version] Generated constants/buildInfo.ts -> buildId:', buildId);

  // 2. Write public/version.json
  fs.writeFileSync(publicVersionPath, JSON.stringify(versionData, null, 2), 'utf-8');
  console.log('[version] Updated public/version.json -> buildId:', buildId);

  // 3. Update BUILD_ID and CACHE_NAME in public/sw.js
  if (fs.existsSync(publicSwPath)) {
    let swContent = fs.readFileSync(publicSwPath, 'utf-8');
    swContent = swContent.replace(
      /const BUILD_ID = ['"][^'"]+['"];/,
      `const BUILD_ID = '${buildId}';`
    );
    swContent = swContent.replace(
      /const CACHE_NAME = ['"][^'"]+['"];/,
      `const CACHE_NAME = 'ayyanar-crm-shell-v' + BUILD_ID;`
    );
    fs.writeFileSync(publicSwPath, swContent, 'utf-8');
    console.log('[version] Updated public/sw.js -> BUILD_ID:', buildId);
  }
}

// 4. Mirror to dist if dist exists
if (fs.existsSync(distDir)) {
  const distVersionPath = path.join(distDir, 'version.json');
  fs.writeFileSync(distVersionPath, JSON.stringify(versionData, null, 2), 'utf-8');

  const distSwPath = path.join(distDir, 'sw.js');
  if (fs.existsSync(publicSwPath)) {
    fs.copyFileSync(publicSwPath, distSwPath);
    console.log('[version] Synchronized public/sw.js -> dist/sw.js');
  }

  const publicHtaccess = path.join(publicDir, '.htaccess');
  const distHtaccess = path.join(distDir, '.htaccess');
  if (fs.existsSync(publicHtaccess)) {
    fs.copyFileSync(publicHtaccess, distHtaccess);
    console.log('[version] Synchronized public/.htaccess -> dist/.htaccess');
  }
}
